# Compute the rank of your design matrix X
rank_X = np.linalg.matrix_rank(X)
n_samples, n_features = X.shape
print(f"X is {n_samples} x {n_features}.  rank(X) = {rank_X}")

# Compare rank(X) to the number of features.
if rank_X == n_features:
    print(f"rank(X) = {rank_X} = p = {n_features}: X has full column rank, "
          "so the columns (features) are linearly independent.")
else:
    print(f"rank(X) = {rank_X} < p = {n_features}: the columns are linearly dependent "
          "(at least one feature is redundant).")
# Are the columns of X linearly independent? Print a short conclusion.
sv = np.linalg.svd(X, compute_uv=False)
print("Singular values:", sv)
print(f"Condition number: {sv[0] / sv[-1]:.4f}")

