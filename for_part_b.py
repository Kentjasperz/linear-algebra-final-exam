X_raw, y = data['X_raw'], data['y']
feature_names = data['feature_names'].tolist()
print('Loaded X_raw:', X_raw.shape, ' y:', y.shape)

# Build the design matrix X (rows = samples, columns = features).
# X_raw is already a clean numeric matrix (4 numeric features, no missing values),
# so we only need to make sure it is a float array.
X = np.asarray(X_raw, dtype=float)
n, p = X.shape
print("X shape:", X.shape)
print(f"n = {n} samples, p = {p} features: {feature_names}")

# Compute the matrix product X^T X  (p x n) @ (n x p) -> (p x p)
XtX = X.T @ X
print("X^T X shape:", XtX.shape)
print(XtX)
print("Symmetric?", np.allclose(XtX, XtX.T))

# Inspect one off-diagonal entry of X^T X (pick any i != j)
i, j = 0, 1   # Attendance and Hours_Studied
print(f"(X^T X)[{i},{j}] = {XtX[i, j]:.4f}  -- corresponds to features "
      f"'{feature_names[i]}' and '{feature_names[j]}'")

# Check: it equals the dot product of the two columns
print("Dot product of the two columns:", X[:, i] @ X[:, j])

